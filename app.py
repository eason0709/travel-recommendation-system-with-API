def get_confidence_level(confidence):

    if confidence >= 0.70:
        return (
            "High",
            "模型對此 cluster 判斷信心較高，可主要參考目前的 cluster label 與推薦結果。"
        )

    if confidence >= 0.40:
        return (
            "Medium",
            "模型對此 cluster 判斷信心中等，建議同時參考 Top probability clusters。"
        )

    return (
        "Low",
        "模型對此 cluster 判斷信心偏低，代表使用者偏好可能分散於多個 cluster，不建議只依賴單一 label。"
    )


